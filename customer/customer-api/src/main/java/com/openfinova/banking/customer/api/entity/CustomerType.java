package com.openfinova.banking.customer.api.entity;

/**
 * Enumeration of customer types (Individual vs Business).
 */
public enum CustomerType {
    /**
     * An individual person.
     */
    INDIVIDUAL,

    /**
     * A corporate entity or business.
     */
    BUSINESS,

    /**
     * A trust or other legal entity.
     */
    TRUST
}
